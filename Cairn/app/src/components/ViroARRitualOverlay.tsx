const STRAND_BASE_SCALE = 1.0;

// Type aliases — same normalisation as ViroAROverlay so old DB rows keep working
const TYPE_REMAP: Record<string, keyof typeof RITUAL_TEX> = {
  water: 'supply',
  free:  'cairn',
  hut:   'cairn',
};
function normalizeType(t: string): keyof typeof RITUAL_TEX {
  if (t in RITUAL_TEX) return t as keyof typeof RITUAL_TEX;
  return TYPE_REMAP[t] ?? 'cairn';
}

// ── Constants ──────────────────────────────────────────────────
// Eye-level offset: place ritual centre slightly below ARKit camera Y so
// user looks down at it (same logic as ViroAROverlay v68 — GPS altitude is
// unreliable, anchor relative to camera height instead).
const RITUAL_GROUND_OFFSET_M = -1.2;
// Visibility range — beyond this, ritual circle is hidden (edge arrows
// take over, same threshold as production overlay).
const VISIBLE_RANGE_M = 50;
const NEAR_THRESHOLD_M = 10;
// Ritual circle physical size. v2 (post-v133 feedback): 2.0m → 0.6m.
// 2m felt like standing inside a fortress; 0.6m = wash-basin scale lets the
// user see the whole ring + strands in one glance even at 1m distance.
const RITUAL_BASE_SIZE_M = 0.6;
// Stable tracking settle window (ms). ARKit briefly reports TRACKING_NORMAL
// during relocalisation while the world transform is still being corrected.
// Production ViroAROverlay uses 1500ms to prevent the "flag flies into the
// sky" bug, but the ritual circle is anchored to the ground (y is constant)
// so a brief world-frame transient is much less visually catastrophic.
// Shorter settle = faster recovery after putting the phone down + picking
// it up (a common interaction the user explicitly flagged in M1 testing).
const TRACKING_SETTLE_MS = 400;

// ── GPS → ARKit world coords ──────────────────────────────────
// Identical math to ViroAROverlay.gpsToArWorld but inlined to keep this
// file self-contained.
function gpsToArWorld(
  origin: { lat: number; lng: number; alt?: number | null },
  target: { lat: number; lng: number; alt?: number | null },
): [number, number, number] {
  const dLat = target.lat - origin.lat;
  const dLng = target.lng - origin.lng;
  const cosLat = Math.cos((origin.lat * Math.PI) / 180);
  const northM = dLat * 111000;
  const eastM = dLng * 111000 * cosLat;
  return [eastM, RITUAL_GROUND_OFFSET_M, -northM];
}

interface CairnWorldPos {
  id: string;
  type: string;
  x: number; y: number; z: number;
  dist: number;
}

interface Props {
  markers: Marker[];
  userPos: { lat: number; lng: number; alt?: number | null } | null;
  userHeading: number | null;
  onStatus?: (status: { glReady: boolean; cairnCount: number }) => void;
  onCairnPress?: (markerId: string) => void;
}

// ─────────────────────────────────────────────────────────────────
// AR scene (inner — accesses viroAppProps via polling, same pattern as
// ViroAROverlay because viroAppProps is mutated in-place not via React state).
// ─────────────────────────────────────────────────────────────────
function RitualARScene(props: any) {
  const [liveProps, setLiveProps] = useState<{
    arkitOrigin: { lat: number; lng: number; alt?: number | null } | null;
    markers: Marker[];
    onCairnPress?: (id: string) => void;
  }>(() => {
    const p = props.sceneNavigator?.viroAppProps ?? {};
    return {
      arkitOrigin: p.arkitOrigin ?? null,
      markers: p.markers ?? [],
      onCairnPress: p.onCairnPress,
    };
  });

  useEffect(() => {
    const id = setInterval(() => {
      const p = props.sceneNavigator?.viroAppProps ?? {};
      setLiveProps(prev => {
        const nextMarkers: Marker[] = p.markers ?? [];
        if (
          prev.arkitOrigin === p.arkitOrigin &&
          prev.markers.length === nextMarkers.length &&
          prev.onCairnPress === p.onCairnPress
        ) return prev;
        return {
          arkitOrigin: p.arkitOrigin ?? null,
          markers: nextMarkers,
          onCairnPress: p.onCairnPress,
        };
      });
    }, 500);
    return () => clearInterval(id);
  }, []);

  const { arkitOrigin, markers, onCairnPress } = liveProps;
  const [tracking, setTracking] = useState(false);
  const [stableTracking, setStableTracking] = useState(false);
  const [materialsReady, setMaterialsReady] = useState(false);

  // ── Register materials + animations (deferred to mount, RN-safe) ──
  useEffect(() => {
    try {
      const types = ['danger', 'supply', 'junction', 'scenic', 'cairn'] as const;
      // Per-type colour for strand tinting. v3 (post-v134 feedback): users
      // report strands still appear white. Diagnostic: use saturated primary
      // colours so we can verify if material assignment is working at all.
      // If strands STILL look white in v135 → material isn't being applied
      // (likely GLB ships without material reference, Viro defaults to white).
      // If strands turn coloured → just need to dim further.
      const STRAND_TINT: Record<string, string> = {
        danger:   '#ff0000',  // pure red — diagnostic
        supply:   '#00ff00',  // pure green
        junction: '#ff8800',  // orange
        scenic:   '#0044ff',  // pure blue
        cairn:    '#ffaa00',  // amber gold
      };
      const mats: Record<string, any> = {};
      for (const t of types) {
        // Ritual ground circle (unchanged from M1)
        mats[`ritual${t}`] = {
          lightingModel: 'Constant',
          diffuseTexture: RITUAL_TEX[t],
          blendMode: 'Add',
          writesToDepthBuffer: false,
          readsFromDepthBuffer: true,
        };
        // Strand material — one per type. v4 (post-v135 diagnostic): logs
        // confirmed strands ARE loading (ritualAR:strand-loaded × 5) but
        // user sees nothing. Two suspects:
        //   1. v135 Alpha blend × low-alpha texture = invisible
        //   2. GLB radius 0.04m × Alpha = nearly transparent thin wisp
        // v4 fix: drop the texture entirely, use solid colour material.
        // If v136 strands appear → texture alpha was the problem.
        // If still invisible → GLB is too thin to see at 1m, regenerate
        //   thicker.
        const cap = t.charAt(0).toUpperCase() + t.slice(1);
        mats[`strand${cap}`] = {
          lightingModel: 'Constant',
          diffuseColor: STRAND_TINT[t],
          // No diffuseTexture, no blendMode — solid opaque tube.
          writesToDepthBuffer: true,
          readsFromDepthBuffer: true,
        };
      }
      ViroMaterials.createMaterials(mats);

      // Animations: slow rotation around Y for the ground ring + 5 small
      // independent sway animations for the strand wrappers. Each strandSway
      // is a single non-chained relative rotation looped — small enough that
      // looping `+=N` doesn't visually drift (delta accumulates but the
      // rotation is so small the user perceives it as gentle oscillation
      // averaged across the cycle).
      // v5 (DS-fidelity): bigger sway range so strands clearly bend in
      // the breeze. Per-strand range 6-12° tilt, period 4-7s. Chained
      // 4-step cycle returns to vertical so they don't drift.
      const sway = (axis: 'rotateZ' | 'rotateX', deg: number, dur: number) => [
        { properties: { [axis]:  deg }, duration: dur, easing: 'EaseInEaseOut' },
        { properties: { [axis]:    0 }, duration: dur, easing: 'EaseInEaseOut' },
        { properties: { [axis]: -deg }, duration: dur, easing: 'EaseInEaseOut' },
        { properties: { [axis]:    0 }, duration: dur, easing: 'EaseInEaseOut' },
      ];

      ViroAnimations.registerAnimations({
        ringSpinSlow: {
          properties: { rotateY: '+=360' },
          duration: 60000,
          easing: 'Linear',
        },
        strandSway0: sway('rotateZ', 7, 1700),
        strandSway1: sway('rotateZ', 9, 2100),
        strandSway2: sway('rotateX', 8, 1500),
        strandSway3: sway('rotateX', 6, 2300),
        strandSway4: sway('rotateZ', 7, 1900),
      });

      setMaterialsReady(true);
      crashLogger.breadcrumb('ritualAR:materials-registered');
    } catch (e: any) {
      crashLogger.breadcrumb(`ritualAR:material-error ${e?.message ?? e}`);
    }
  }, []);

  // ── Tracking state ─────────────────────────────────────────────
  const onTrackingUpdated = useCallback((state: ViroTrackingState, _reason: ViroTrackingReason) => {
    const ok = state === ViroTrackingStateConstants.TRACKING_NORMAL;
    setTracking(ok);
    crashLogger.breadcrumb(`ritualAR:tracking state=${state}`);
  }, []);

  useEffect(() => {
    if (!tracking) {
      setStableTracking(false);
      return;
    }
    const id = setTimeout(() => setStableTracking(true), TRACKING_SETTLE_MS);
    return () => clearTimeout(id);
  }, [tracking]);

  // ── World position computation ────────────────────────────────
  const cairnNodes = useMemo<CairnWorldPos[]>(() => {
    if (!arkitOrigin) return [];
    const out: CairnWorldPos[] = [];
    for (const m of markers) {
      const [x, y, z] = gpsToArWorld(arkitOrigin, m as any);
      const dLat = ((m as any).lat - arkitOrigin.lat) * 111000;
      const cosLat = Math.cos((arkitOrigin.lat * Math.PI) / 180);
      const dLng = ((m as any).lng - arkitOrigin.lng) * 111000 * cosLat;
      const dist = Math.sqrt(dLat * dLat + dLng * dLng);
      if (dist > VISIBLE_RANGE_M) continue;
      out.push({ id: m.id, type: m.type as string, x, y, z, dist });
    }
    return out;
  }, [arkitOrigin, markers]);

  return (
    <ViroARScene onTrackingUpdated={onTrackingUpdated}>
      {/* Soft ambient + warm directional — keeps PNG colours readable
          regardless of real-world lighting. Constant material does NOT
          react to lights but other future layers (text labels) might. */}
      <ViroAmbientLight color="#ffffff" intensity={300} />
      <ViroDirectionalLight color="#ffffff" direction={[0.0, -1.0, -0.5]} intensity={500} />

      {materialsReady && stableTracking && cairnNodes.map((c) => (
        <RitualInstance
          key={c.id}
          id={c.id}
          type={c.type}
          x={c.x}
          y={c.y}
          z={c.z}
          dist={c.dist}
          onPress={onCairnPress}
        />
      ))}
    </ViroARScene>
  );
}

// ─────────────────────────────────────────────────────────────────
// RitualInstance — one marker rendered as ground ritual circle.
// M1 scope: just the circle. Strands + label + debris will be added
// in M2/M3/M4.
// ─────────────────────────────────────────────────────────────────
function RitualInstance(props: {
  id: string;
  type: string;
  x: number; y: number; z: number;
  dist: number;
  onPress?: (id: string) => void;
}) {
  const { id, type, x, y, z, dist, onPress } = props;
  const normalized = normalizeType(type);
  const matName = `ritual${normalized}`;

  // Distance-aware scale: at 0–10m show natural size, fade larger toward
  // 50m so it remains visible from afar without being huge up close.
  let sizeMul: number;
  if (dist <= NEAR_THRESHOLD_M) {
    sizeMul = 1.0;
  } else {
    const t = Math.min(1, (dist - NEAR_THRESHOLD_M) / (VISIBLE_RANGE_M - NEAR_THRESHOLD_M));
    sizeMul = 1.0 + t * 1.5;     // grows to 2.5x at edge of visibility
  }
  const size = RITUAL_BASE_SIZE_M * sizeMul;

  const onPressCb = useCallback(() => {
    crashLogger.breadcrumb(`ritualAR:press id=${id.slice(-6)}`);
    onPress?.(id);
  }, [id, onPress]);

  useEffect(() => {
    const cap = normalized.charAt(0).toUpperCase() + normalized.slice(1);
    crashLogger.breadcrumb(
      `ritualAR:render id=${id.slice(-6)} type=${type} norm=${normalized} dist=${dist.toFixed(1)} size=${size.toFixed(2)} strandMat=strand${cap}`,
    );
  }, [id, type, normalized, dist, size]);

  return (
    <ViroNode position={[x, y, z]} onClick={onPressCb}>
      {/* Outer wrapper handles the slow rotation. Inner quad lies flat on
          the ground (rotation X = -90°). The quad uses Add blend so the
          ring glows additively on top of the camera feed. */}
      <ViroNode
        animation={{ name: 'ringSpinSlow', run: true, loop: true }}
      >
        <ViroQuad
          rotation={[-90, 0, 0]}                // lay flat on ground
          width={size}
          height={size}
          materials={[matName]}
        />
      </ViroNode>

      {/* Chiral strands — 5 GLB ribbon meshes rising from points around the
          ring. Each is a curved S-tube ~40m tall with along-length thickness
          variation baked into the geometry. Materials use Constant lighting
          + Add blend + per-type diffuseColor tint so all 5 strands draw
          from a single neutral white flow texture.
          The strand_a..e.glb meshes have distinct curve shapes; combined with
          per-strand yaw (i * 17°) and per-strand sway animations, no two
          strands look alike.
          Step 4 will add a UV-scroll shaderModifier so the texture appears
          to flow upward inside each strand (DS chiral effect). */}
      {STRAND_OFFSETS.map((off, i) => {
        // v143: pick GLB by curve index AND by marker type — colour is
        // baked into the mesh's PBR material so Viro3DObject's silent
        // ignore-the-materials-prop bug no longer matters.
        const glbForType = STRAND_GLBS[normalized] ?? STRAND_GLBS.cairn;
        return (
          <ViroNode
            key={`strand-${i}`}
            position={[off.x * (RITUAL_BASE_SIZE_M * 0.5), 0.0, off.z * (RITUAL_BASE_SIZE_M * 0.5)]}
            rotation={[0, i * 17, 0]}
            animation={{ name: STRAND_SWAY_ANIMS[i], run: true, loop: true }}
          >
            <Viro3DObject
              source={glbForType[i]}
              type="GLB"
              scale={[STRAND_BASE_SCALE, STRAND_BASE_SCALE, STRAND_BASE_SCALE]}
              onLoadEnd={() => crashLogger.breadcrumb(`ritualAR:strand-loaded i=${i} type=${normalized}`)}
              onError={(event: any) => crashLogger.breadcrumb(`ritualAR:strand-load-fail i=${i} err=${event?.nativeEvent?.error ?? 'unknown'}`)}
            />
          </ViroNode>
        );
      })}
    </ViroNode>
  );
}

// Public ref handle exposed to ARScreen for debugging.
export interface ViroARRitualOverlayHandle {
  /**
   * Take a screenshot of the Viro AR view + dump diagnostic state.
   * Image is base64-encoded and written to telemetry as a special
   * `debug-snapshot` breadcrumb. Backend pulls it via mysql; the
   * scripts/get_debug_snapshot.mjs helper decodes to PNG locally.
   */
  takeDebugSnapshot: () => Promise<{ success: boolean; error?: string }>;
}

// ─────────────────────────────────────────────────────────────────
// Public component — same Props shape as ViroAROverlay so ARScreen
// can swap them with a single ternary.
// ─────────────────────────────────────────────────────────────────
export const ViroARRitualOverlay = forwardRef<ViroARRitualOverlayHandle, Props>(function ViroARRitualOverlay({
  markers,
  userPos,
  userHeading: _userHeading,
  onStatus,
  onCairnPress,
}: Props, ref) {
  const arkitOriginRef = useRef<{ lat: number; lng: number; alt?: number | null } | null>(null);
  const viroNavRef = useRef<any>(null);
  const [originReady, setOriginReady] = useState(false);

  // Expose debug snapshot to parent (ARScreen). Captures the live Viro
  // render + emits diagnostic breadcrumbs with current strand state.
  useImperativeHandle(ref, () => ({
    takeDebugSnapshot: async () => {
      try {
        // ViroARSceneNavigator exposes its native methods on
        // `arSceneNavigator` (the class field), NOT on the component
        // instance directly. v138 used `viroNavRef.current.takeScreenshot`
        // and got 'no-viro-ref' because that method doesn't exist there.
        const nav = (viroNavRef.current as any)?.arSceneNavigator;
        const takeScreenshot = nav?.takeScreenshot;
        if (typeof takeScreenshot !== 'function') {
          const keys = viroNavRef.current ? Object.keys(viroNavRef.current).slice(0, 20).join(',') : 'null';
          const navKeys = nav ? Object.keys(nav).slice(0, 20).join(',') : 'null';
          crashLogger.breadcrumb(`ritualAR:debug-snapshot-no-fn refKeys=[${keys}] navKeys=[${navKeys}]`);
          return { success: false, error: 'takeScreenshot-not-fn' };
        }
        crashLogger.breadcrumb(`ritualAR:debug-snapshot-start markers=${markers.length}`);
        const result = await takeScreenshot('cairn-debug', false);
        crashLogger.breadcrumb(
          `ritualAR:debug-snapshot-result success=${result?.success} url=${result?.url ?? 'none'} err=${result?.errorCode ?? 'none'}`
        );
        if (result?.success && result?.url) {
          // Read png file via fetch on file:// URI → Blob (RN supports this).
          const fileUri = result.url.startsWith('file://') ? result.url : `file://${result.url}`;
          const resp = await fetch(fileUri);
          const blob = await resp.blob();
          const snapshotId = `snap-${Date.now()}`;
          crashLogger.breadcrumb(
            `ritualAR:debug-snapshot-meta id=${snapshotId} bytes=${blob.size} markers=${markers.length}`
          );
          // v142: backend now has /api/debug-snapshot — POST raw PNG
          // bytes directly. No base64, no chunking, no telemetry pollution.
          // 10× simpler + faster than v141's JSONL chunking approach.
          const ts = Date.now();
          const snapMeta = {
            markers: markers.length,
            ts,
          };
          try {
            const metaB64 = global.btoa
              ? global.btoa(JSON.stringify(snapMeta))
              : (require('buffer') as any).Buffer.from(JSON.stringify(snapMeta)).toString('base64');
            const url = `${API_BASE_URL.replace(/\/$/, '')}/api/debug-snapshot`
              + `?id=${encodeURIComponent(snapshotId)}`
              + `&meta=${encodeURIComponent(metaB64)}`;
            const resp = await fetch(url, {
              method: 'POST',
              headers: {
                'Content-Type': 'image/png',
                'X-Cairn-Device-Os': 'ios',
                'X-Cairn-App-Version': '0.2.0',
                'X-Cairn-Ar-Mode': 'ritual',
              },
              body: blob,
            });
            const status = resp.status;
            const respText = await resp.text().catch(() => '');
            crashLogger.breadcrumb(`ritualAR:debug-snapshot-uploaded sid=${snapshotId} status=${status} bytes=${blob.size} resp=${respText.slice(0, 100)}`);
            if (status >= 200 && status < 300) {
              return { success: true, error: `OK ${status} sid=${snapshotId} bytes=${blob.size}` };
            }
            return { success: false, error: `http ${status}: ${respText.slice(0, 100)}` };
          } catch (e: any) {
            return { success: false, error: `fetch-fail: ${e?.message ?? e}` };
          }
        }
        return { success: false, error: result?.errorCode ?? 'no-url' };
      } catch (e: any) {
        crashLogger.breadcrumb(`ritualAR:debug-snapshot-error ${e?.message ?? e}`);
        return { success: false, error: String(e?.message ?? e) };
      }
    },
  }), [markers.length]);

  // Reuse the SAME persisted origin as ViroAROverlay so switching modes
  // doesn't move the markers (both renderers share the world frame).
  const persistedArOrigin = useMarkerStore(s => s.arOrigin);
  const setArOriginIfMissing = useMarkerStore(s => s.setArOriginIfMissing);

  useEffect(() => {
    if (persistedArOrigin) {
      arkitOriginRef.current = { ...persistedArOrigin };
      setOriginReady(true);
      crashLogger.breadcrumb(
        `ritualAR:origin-restored lat=${persistedArOrigin.lat.toFixed(6)} lng=${persistedArOrigin.lng.toFixed(6)}`,
      );
    } else {
      arkitOriginRef.current = null;
      setOriginReady(false);
      crashLogger.breadcrumb('ritualAR:origin-reset');
    }
    return () => { crashLogger.breadcrumb('ritualAR:session-ended'); };
  }, []);

  useEffect(() => {
    if (!arkitOriginRef.current && userPos) {
      const o = { lat: userPos.lat, lng: userPos.lng, alt: userPos.alt ?? null };
      arkitOriginRef.current = o;
      setOriginReady(true);
      setArOriginIfMissing(o);
      crashLogger.breadcrumb(
        `ritualAR:origin-set lat=${userPos.lat.toFixed(6)} lng=${userPos.lng.toFixed(6)}`,
      );
    }
  }, [userPos?.lat, userPos?.lng, userPos?.alt]);

  useEffect(() => {
    if (onStatus) onStatus({ glReady: originReady, cairnCount: markers.length });
  }, [markers.length, onStatus, originReady]);

  useEffect(() => {
    crashLogger.breadcrumb(`ritualAR:overlay-mount markers=${markers.length}`);
    return () => { crashLogger.breadcrumb('ritualAR:overlay-unmount'); };
  }, []);

  if (!userPos || !arkitOriginRef.current) return null;

  return (
    <View style={StyleSheet.absoluteFillObject} pointerEvents="box-none">
      <ViroARSceneNavigator
        ref={viroNavRef}
        autofocus
        worldAlignment="GravityAndHeading"
        provider="none"
        hdrEnabled
        bloomEnabled
        initialScene={{ scene: RitualARScene as any }}
        viroAppProps={{
          arkitOrigin: arkitOriginRef.current,
          markers,
          onCairnPress,
        }}
        style={StyleSheet.absoluteFillObject}
      />
    </View>
  );
});
